def check_andong(line_dizhi, day_dizhi, is_dong_yao=False):
    """
    判断静爻是否暗动。

    规则：静爻被日辰所冲，则为暗动（旺相之爻暗动有力，休囚之爻日破）。

    参数：
        line_dizhi: 爻的地支
        day_dizhi: 日辰地支
        is_dong_yao: 是否已是动爻

    返回：
        str: "暗动" / "日破" / ""
    """
    if is_dong_yao:
        return ""
    if DIZHI_CHONG.get(line_dizhi) == day_dizhi:
        # 旺相者暗动，休囚者日破——此处仅标识为暗动，
        # 具体旺衰由爻力评分模块进一步判断
        return "暗动"
    return ""


