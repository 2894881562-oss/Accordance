# 六亲与五行反查（供用神系统使用）
# ═══════════════════════════════════════════════════════════

def get_element_by_liuqin(liuqin_name, palace_wuxing):
    """
    根据宫五行与六亲名反查该六亲对应的五行。

    规则：
    - 兄弟 → 同我（宫五行）
    - 子孙 → 我生
    - 妻财 → 我克
    - 官鬼 → 克我
    - 父母 → 生我
    """
    if liuqin_name == "兄弟":
        return palace_wuxing
    if liuqin_name == "子孙":
        return WUXING_SHENG.get(palace_wuxing, "土")
    if liuqin_name == "妻财":
        return WUXING_KE.get(palace_wuxing, "土")
    if liuqin_name == "官鬼":
        for k, v in WUXING_KE.items():
            if v == palace_wuxing:
                return k
    if liuqin_name == "父母":
        for k, v in WUXING_SHENG.items():
            if v == palace_wuxing:
                return k
    return "土"
