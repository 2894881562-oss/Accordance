# 地支顺序
DIZHI_ORDER = ["子", "丑", "寅", "卯", "辰", "巳",
               "午", "未", "申", "酉", "戌", "亥"]


def get_shier_changsheng(tiangan, dizhi):
    """
    查询天干地支对应的十二长生状态
    参数：
        tiangan: 天干（甲、乙、丙、丁、戊、己、庚、辛、壬、癸）
        dizhi: 地支（子、丑、寅、卯、辰、巳、午、未、申、酉、戌、亥）
    返回：
        str: 十二长生状态
    """
    group = TIANGAN_CHANGSHENG_GROUP.get(tiangan, tiangan)

    if group not in WUXING_SHIER_CHANGSHENG:
        return "未知"

    start_dizhi = WUXING_SHIER_CHANGSHENG[group]
    start_index = DIZHI_ORDER.index(start_dizhi)
    target_index = DIZHI_ORDER.index(dizhi)

    # 阳干顺行，阴干逆行
    gan = group[0]
    if gan in ["甲", "丙", "戊", "庚", "壬"]:
        offset = (target_index - start_index) % 12
    else:
        offset = (start_index - target_index) % 12

    return SHIER_CHANGSHENG_ORDER[offset]


