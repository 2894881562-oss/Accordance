def get_kangxi_stroke(char):
    """返回单字康熙笔画；未覆盖时返回 None。"""
    return KANGXI_STROKES.get(char)


def analyze_text_strokes(text):
    """返回文本笔画分析结果。"""
    details = []
    missing = []
    total = 0
    for char in text:
        stroke = get_kangxi_stroke(char)
        if stroke is None:
            missing.append(char)
            details.append({"char": char, "stroke": None})
            continue
        total += stroke
        details.append({"char": char, "stroke": stroke})
    return {"total": total, "details": details, "missing": missing}
