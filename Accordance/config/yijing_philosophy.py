# ── 辅助函数 ──

def get_hexagram_wisdom(hexagram_name: str) -> str:
    """获取某卦的易经人文智慧。"""
    return HEXAGRAM_HUMAN_WISDOM.get(
        hexagram_name,
        "卦有吉凶，人有进退。守正持中，知时知止，方为学易之道。",
    )


def get_trigram_virtue(gua_name: str) -> dict:
    """获取某八卦的德行修养指引。"""
    return TRIGRAM_VIRTUE_GUIDE.get(
        gua_name,
        {
            "virtue": "守正持中",
            "teaching": "坚守正道，保持中道，不被外界动摇。",
            "caution": "不失其正，不违其时，不妄其行。",
        },
    )


def get_situation_advice(ji_xiong_level: str) -> str:
    """根据吉凶等级给出人本建议。"""
    if "上上" in ji_xiong_level or "上中" in ji_xiong_level:
        return SITUATION_HUMAN_ADVICE["大吉大利"]
    if "中上" in ji_xiong_level:
        return SITUATION_HUMAN_ADVICE["吉中藏凶"]
    if "中下" in ji_xiong_level:
        return SITUATION_HUMAN_ADVICE["凶中藏吉"]
    if "下下" in ji_xiong_level or "下中" in ji_xiong_level:
        return SITUATION_HUMAN_ADVICE["大凶之兆"]
    return SITUATION_HUMAN_ADVICE["平平之中"]


def build_human_guidance(hexagram_name: str, ji_xiong: str,
                          shang_gua_name: str = "", xia_gua_name: str = "") -> str:
    """综合生成人本指引。"""
    wisdom = get_hexagram_wisdom(hexagram_name)
    situation = get_situation_advice(ji_xiong)

    virtue_text = ""
    if shang_gua_name:
        v = get_trigram_virtue(shang_gua_name)
        virtue_text += f"\n上卦{shang_gua_name}之德：{v['teaching']}"
    if xia_gua_name:
        v = get_trigram_virtue(xia_gua_name)
        virtue_text += f"\n下卦{xia_gua_name}之德：{v['teaching']}"

    return (
        f"\n{'─' * 60}"
        f"\n【易经人本指引】"
        f"\n{wisdom}"
        f"\n{situation}"
        f"{virtue_text}"
        f"\n{'─' * 60}"
    )
